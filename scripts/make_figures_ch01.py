#!/usr/bin/env python
"""產生第 1 章用到的 figures/*.txt。

  * ch01_scale   棋盤大小 -> 局面數上界（算出來的）
  * ch01_spine   五層骨架預覽表（**不是算出來的** —— 它是全書的目錄）

第 1 章是預覽章，所以它唯一該算的東西是「這個問題有多大」。
其餘的數字都在後面十三章各自的章節裡算，這裡只負責指路。
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from go_core.board import Board                                     # noqa: E402

OUT = ROOT / "figures"
OUT.mkdir(exist_ok=True)


def scale():
    rows = [f"  {'棋盤':<10}{'交叉點':>8}{'局面數上界 3^(n*n)':>24}"
            f"{'本書算得動嗎':>16}",
            "  " + "-" * 66]
    solved = {2: "算得動（本書解了）", 3: "算得動（本書解了）",
              4: "算不動了", 7: "算不動", 9: "算不動", 19: "算不動"}
    for n in (2, 3, 4, 7, 9, 19):
        pts = n * n
        ub = 3 ** pts
        digits = len(str(ub))
        shown = f"3^{pts} ~ 10^{digits - 1}"
        rows.append(f"  {str(n) + ' 路':<10}{pts:>8}{shown:>24}"
                    f"{solved[n]:>16}")
    rows.append("")
    rows.append("  「上界」是因為很多字串排列在圍棋規則下不合法（例如沒氣的棋子）。")
    rows.append("  但即使打對折再打對折，19 路的 10^172 也還是 10^172。")
    rows.append("")
    rows.append("  對照：可觀測宇宙的原子數大約 10^80。")
    rows.append("  所以本書所有【精確】的計算都在 3 路盤上做 —— 那是有答案的地方。")
    return "\n".join(rows)


SPINE = """
  五層骨架                                    （全書目錄，不是計算結果）
  ======================================================================

  層   符號        它回答的問題                        章
  ----------------------------------------------------------------------
  1   L(S)        這些棋子是【一塊】嗎？還剩幾口氣？    2, 8
                  -> 連通性。棋盤是一張圖，棋串是連通分量，氣是鄰點集合。

  2   Inv(S)      這塊棋【死了沒有】？                  3, 4, 12
                  -> 不變量。兩個眼是一個對手動不了的量，所以它是活的。

  3   t(G)        現在【哪裡最大】？                    6, 7, 11
                  -> 溫度。局部可以相加，而溫度就是「這裡還值多少」。

  4   I(v)        這一帶是【誰的】？                    9
                  -> 場。唯一整層標黃的一層：它是啟發式，而且證明了
                     它算不出死活（定理 9.5）。

  5   V(s)        這一手【值多少目】？                  10, 13
                  -> 值函數。前四層都是它的便宜近似。只有小盤算得出來。

  例外  劫          「不能立刻提回來」                  5
                  -> 它讓局部不能相加，所以它不是第六層，是一個貫穿的例外。

  ======================================================================
  第 14 章把這五層架在 3 路盤 1,742 個已解局面上量了一次：
  死活 = 溫度 > 場 > 連通性（552 次分歧零敗），而仍有 9.0% 的局面
  五層一句話也說不出來。那 9% 是這本書欠讀者的帳，它印在書裡。
"""


FIGURES = {
    "ch01_scale": scale,
    "ch01_spine": lambda: SPINE.strip("\n"),
}


def main():
    for name, fn in FIGURES.items():
        (OUT / f"{name}.txt").write_text(fn().rstrip("\n") + "\n",
                                         encoding="utf-8", newline="\n")
        print(f"  寫出 {name}.txt")


if __name__ == "__main__":
    main()
